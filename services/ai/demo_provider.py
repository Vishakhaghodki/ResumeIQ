from .base import AIProvider


class DemoProvider(AIProvider):
    """Offline, template-based feedback used when no API key is configured."""

    name = "demo"
    is_live = False

    def generate_feedback(self, ctx):
        m, a = ctx["match_score"], ctx["ats_score"]
        level = "strong" if m >= 75 else "moderate" if m >= 50 else "low"
        parts = [
            f"[DEMO MODE - rule-based feedback, not generated by an AI model]\n\n"
            f"Overall impression: Your resume is a {level} match ({m}/100) for \"{ctx['job_title']}\" "
            f"with an ATS-readiness score of {a}/100."
        ]
        strengths = []
        if ctx["matched"]:
            strengths.append(f"You already cover {len(ctx['matched'])} required skill(s): "
                             + ", ".join(ctx["matched"][:6]) + ".")
        if a >= 70:
            strengths.append("Your resume structure is readable by most ATS software.")
        if not strengths:
            strengths.append("You have a base to build on; focus on tailoring it to the role.")
        parts.append("Strengths:\n" + "\n".join(f"- {s}" for s in strengths))
        improvements = []
        if ctx["missing"]:
            improvements.append("Show evidence of " + ", ".join(ctx["missing"][:4])
                                + " (only if you have it) in a project or experience bullet.")
        if ctx["missing_keywords"]:
            improvements.append("Mirror the job's wording, e.g. " + ", ".join(ctx["missing_keywords"][:5]) + ".")
        for issue in ctx["ats_issues"][:2]:
            improvements.append(f"Fix ATS issue: {issue}.")
        if not improvements:
            improvements.append("Quantify your achievements to stand out further.")
        parts.append("Improvements:\n" + "\n".join(f"- {s}" for s in improvements))
        parts.append("Tip: set ANTHROPIC_API_KEY or OPENAI_API_KEY in your .env file to enable "
                     "personalised AI feedback with rewrite examples.")
        return "\n\n".join(parts)
